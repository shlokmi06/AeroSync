def create_scheduled_datetime(df):

    hhmm = df["SCHEDULED_DEPARTURE"].round().astype("Int64")

    hour = (hhmm // 100).astype("Int64")
    minute = (hhmm % 100).astype("Int64")

    valid = (
        hhmm.notna()
        & (hour <= 24)
        & (minute < 60)
        & ((hour < 24) | (minute == 0))
    )

    result = pd.Series(
        pd.NaT,
        index=df.index,
        dtype="datetime64[ns]"
    )

    result.loc[valid] = (
        df.loc[valid, "FLIGHT_DATE"]
        + pd.to_timedelta(hour.loc[valid], unit="h")
        + pd.to_timedelta(minute.loc[valid], unit="m")
    )

    return result

