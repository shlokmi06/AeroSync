for code in top_airports:

    airport = airports[
        airports["IATA_CODE"] == code
    ]

    if airport.empty:
        continue

    lat = airport.iloc[0]["LATITUDE"]
    lon = airport.iloc[0]["LONGITUDE"]

    if pd.isna(lat) or pd.isna(lon):
        continue

    url = "https://archive-api.open-meteo.com/v1/archive"

    params = {
        "latitude": float(lat),
        "longitude": float(lon),
        "start_date": "2015-01-01",
        "end_date": "2015-12-31",
        "hourly": weather_variables,
        "timezone": "auto",
        "timeformat": "unixtime"
    }

    response = requests.get(
        url, params=params, timeout=90
    )

    response.raise_for_status()

    data = response.json()
    hourly = data["hourly"]

    weather = pd.DataFrame(hourly)

    # Convert UTC Unix timestamps to local airport time
    weather["WEATHER_TIMESTAMP"] = (
        pd.to_datetime(
            weather["time"],
            unit="s",
            utc=True
        )
        .dt.tz_convert(data["timezone"])
        .dt.tz_localize(None)
    )

    weather.drop(columns=["time"], inplace=True)

    weather["ORIGIN_AIRPORT"] = code

    airport_weather_data.append(weather)

    print("Downloaded weather for:", code)

